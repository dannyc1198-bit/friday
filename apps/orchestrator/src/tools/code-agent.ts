// ─── Security: only these dirs can be built into ──────────────────
const ALLOWED_BUILD_DIRS = [
  "C:\\Users\\12368\\jarvis",
  "C:\\Users\\12368\\wavelength",
  "C:\\Users\\12368\\projects",
  "C:\\Users\\12368\\Desktop\\projects",
  "C:\\Users\\12368\\Documents\\projects",
];

// Tool change log (security requirement)
const LOG_FILE = join(
  process.env.USERPROFILE || "C:\\Users\\12368",
  "jarvis", "logs", "tool-changes.log"
);

function logToolChange(entry: string): void {
  try {
    const dir = join(process.env.USERPROFILE || "C:\\Users\\12368", "jarvis", "logs");
    if (!existsSync(dir)) mkdirSync(dir, { recursive: true });
    appendFileSync(LOG_FILE, `[${new Date().toISOString()}] ${entry}\n`);
  } catch { /* non-critical */ }
}

function isAllowedDir(dir: string): boolean {
  const normalized = dir.replace(/\//g, "\\");
  return ALLOWED_BUILD_DIRS.some((allowed) =>
    normalized.toLowerCase().startsWith(allowed.toLowerCase())
  );
}

// ─── Run a command and stream output ─────────────────────────────

async function runWithOutput(
  cmd: string,
  args: string[],
  cwd: string,
  onOutput: (line: string) => void,
  signal?: AbortSignal
): Promise<{ exitCode: number; output: string }> {
  return new Promise((resolve) => {
    const proc = spawn(cmd, args, {
      cwd,
      shell: true,
      stdio: ["ignore", "pipe", "pipe"],
      windowsHide: true,
    });

    let output = "";

    proc.stdout.on("data", (d: Buffer) => {
      const lines = d.toString().split("\n").filter(Boolean);
      for (const line of lines) {
        output += line + "\n";
        onOutput(line);
      }
    });

    proc.stderr.on("data", (d: Buffer) => {
      const lines = d.toString().split("\n").filter(Boolean);
      for (const line of lines) {
        output += `[err] ${line}\n`;
        onOutput(`[err] ${line}`);
      }
    });

    signal?.addEventListener("abort", () => proc.kill("SIGTERM"));

    proc.on("close", (code) => resolve({ exitCode: code ?? 1, output }));
  });
}

// ─── Tools ────────────────────────────────────────────────────────

const tools: Tool[] = [

  // ── Build with Claude Code ────────────────────────────────────
  {
    name: "code_agent_build",
    description: "Spawn Claude Code to build something. Danny describes what to build, FRIDAY runs claude CLI and streams the output. Use for: landing pages, apps, components, scripts.",
    category: "Code Agent",
    parameters: [
      { name: "spec",       type: "string", description: "What to build — be specific (e.g. 'landing page for No Problem Plumbing plumber in Chilliwack, BC. Services: drain cleaning, emergency repair, commercial. Blue color scheme.')", required: true },
      { name: "output_dir", type: "string", description: "Directory to build into (must be under Danny's project folders)", required: true },
      { name: "deploy_to_netlify", type: "boolean", description: "Auto-deploy to Netlify after build (default false)", required: false },
    ],
    execute: async (params): Promise<ToolResult> => {
      const spec      = params.spec as string;
      const outputDir = params.output_dir as string;
      const deploy    = !!params.deploy_to_netlify;

      // Security: validate output directory
      if (!isAllowedDir(outputDir)) {
        return {
          toolCallId: "",
          success: false,
          error: `Build directory not allowed: ${outputDir}. Must be under: ${ALLOWED_BUILD_DIRS.join(", ")}`,
        };
      }

      // Create output dir if needed
      if (!existsSync(outputDir)) mkdirSync(outputDir, { recursive: true });

      // Write spec to temp file for Claude Code to read
      const specFile = join(outputDir, "_FRIDAY_BUILD_SPEC.md");
      writeFileSync(specFile, `# Build Specification\n\n${spec}\n\nGenerated by FRIDAY at ${new Date().toISOString()}\n`);

      logToolChange(`code_agent_build: spec="${spec.slice(0, 100)}" dir="${outputDir}"`);

      const outputLines: string[] = [];
      const onOutput = (line: string) => {
        outputLines.push(line);
        // Cap memory usage
        if (outputLines.length > 500) outputLines.shift();
      };

      // Run claude CLI with the spec
      const claudeArgs = [
        "--print",
        `Read _FRIDAY_BUILD_SPEC.md and build exactly what it describes. Create all files needed. Make it production-ready.`,
      ];

      const { exitCode, output } = await runWithOutput(
        "claude",
        claudeArgs,
        outputDir,
        onOutput
      );

      if (exitCode !== 0) {
        return {
          toolCallId: "",
          success: false,
          error: `Claude Code exited with code ${exitCode}. Last output: ${outputLines.slice(-5).join(" | ")}`,
          data: output.slice(-2000),
        };
      }

      let result = `Build complete in ${outputDir}. ${outputLines.length} lines of output.`;

      // Deploy to Netlify if requested
      if (deploy && config.netlify.authToken) {
        onOutput("[FRIDAY] Deploying to Netlify...");

        const deployResult = await runWithOutput(
          "netlify",
          ["deploy", "--prod", "--dir", outputDir],
          outputDir,
          onOutput
        );

        if (deployResult.exitCode === 0) {
          const urlMatch = deployResult.output.match(/https:\/\/[^\s]+\.netlify\.app/);
          const url = urlMatch ? urlMatch[0] : "unknown URL";
          result += ` Deployed to Netlify: ${url}`;
        } else {
          result += " Netlify deploy failed — check logs.";
        }
      }

      return { toolCallId: "", success: true, data: result };
    },
  },

  // ── Deploy existing dir to Netlify ────────────────────────────
  {
    name: "code_agent_deploy",
    description: "Deploy an existing directory to Netlify. Use after a build is done and Danny wants to go live.",
    category: "Code Agent",
    parameters: [
      { name: "dir",       type: "string",  description: "Directory to deploy", required: true },
      { name: "site_name", type: "string",  description: "Netlify site name (optional — creates new site if not set)", required: false },
      { name: "confirmed", type: "boolean", description: "Danny has confirmed the deploy", required: true },
    ],
    execute: async (params): Promise<ToolResult> => {
      if (!params.confirmed) {
        return { toolCallId: "", success: false, error: "Deploy not confirmed — show Danny the build first and ask permission." };
      }

      const dir      = params.dir as string;
      const siteName = params.site_name as string | undefined;

      if (!isAllowedDir(dir)) {
        return { toolCallId: "", success: false, error: `Deploy directory not allowed: ${dir}` };
      }
      if (!existsSync(dir)) {
        return { toolCallId: "", success: false, error: `Directory does not exist: ${dir}` };
      }
      if (!config.netlify.authToken) {
        return { toolCallId: "", success: false, error: "NETLIFY_AUTH_TOKEN not configured" };
      }

      const args = ["deploy", "--prod", "--dir", dir];
      if (siteName) args.push("--site", siteName);

      const lines: string[] = [];
      const { exitCode, output } = await runWithOutput("netlify", args, dir, (l) => lines.push(l));

      if (exitCode !== 0) {
        return { toolCallId: "", success: false, error: `Deploy failed: ${lines.slice(-3).join(" | ")}` };
      }

      const urlMatch = output.match(/https:\/\/[^\s]+\.netlify\.app/);
      const url = urlMatch ? urlMatch[0] : "check Netlify dashboard";

      logToolChange(`code_agent_deploy: dir="${dir}" url="${url}"`);
      return { toolCallId: "", success: true, data: `Deployed. Live at: ${url}` };
    },
  },
];

export function registerCodeAgentTools(): void {
  tools.forEach((t) => toolRegistry.register(t));
}
